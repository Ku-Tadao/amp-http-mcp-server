#!/usr/bin/env node
// Extracts AMP's API spec from a browser HAR of the panel's /api page and writes
// src/amp-api-spec.json plus the amp-mcp skill's grep-able method reference.
//
//   node scripts/extract-api-spec.mjs api/amp.example.com.har
//
// Capture the HAR while logged in: GetAPISpec is session-scoped, and without a
// session AMP returns only the pre-login methods. The HAR holds a session ID, so
// it stays gitignored; nothing from its headers or request bodies is written out.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const harPath = process.argv[2];
if (!harPath) {
  console.error("Usage: node scripts/extract-api-spec.mjs <file.har>");
  process.exit(1);
}

const entries = JSON.parse(readFileSync(harPath, "utf8")).log.entries;
const responses = (method) =>
  entries
    .filter((e) => new URL(e.request.url).pathname === `/API/Core/${method}` && e.response.status === 200)
    .map((e) => JSON.parse(e.response.content.text));

const specs = responses("GetAPISpec");
const count = (spec) => Object.values(spec).reduce((n, methods) => n + Object.keys(methods).length, 0);
if (!specs.length) throw new Error("No Core/GetAPISpec response in the HAR.");
specs.sort((a, b) => count(a) - count(b));
const full = specs.at(-1);
// Only trust the smallest spec as the pre-login surface if the page really fetched both.
const preLogin = specs.length > 1 && count(specs[0]) < count(full) ? specs[0] : null;
const info = responses("GetModuleInfo")[0];

writeFileSync(path.join(root, "src", "amp-api-spec.json"), `${JSON.stringify(full, null, 2)}\n`);

const signature = (p) => `${p.Name}${p.Optional ? "?" : ""}: ${p.TypeName}`;
const enums = (p) =>
  p.ParamEnumValues ? ` ${p.Name} ∈ {${Object.entries(p.ParamEnumValues).map(([k, v]) => `${k}=${v}`).join(", ")}}` : "";
const lines = [];
for (const [module, methods] of Object.entries(full)) {
  const names = Object.keys(methods).sort();
  if (!names.length) continue;
  lines.push(`## ${module}`, "");
  for (const name of names) {
    const m = methods[name];
    const perms = m.RequiredPermissions.length ? ` [${m.RequiredPermissions.join(", ")}]` : "";
    const desc = m.Description ? ` — ${m.Description}` : "";
    lines.push(`- \`${module}/${name}(${m.Parameters.map(signature).join(", ")}) → ${m.ReturnTypeName}\`${perms}${m.Parameters.map(enums).join("")}${desc}`);
  }
  lines.push("");
}

const version = info ? `AMP ${info.AMPVersion} (build ${info.AMPBuild}, ${info.BuildSpec}), module ${info.ModuleName}` : "unknown AMP version";
const doc = `# AMP API reference

Generated by \`scripts/extract-api-spec.mjs\` from a HAR of the panel's \`/api\` page: ${version},
${count(full)} methods. Regenerate after an AMP upgrade rather than editing by hand.

This is the **controller's** spec. Game modules and instance plugins (for example
\`MinecraftModule\`, \`GenericModule\`, \`LocalFileBackupPlugin\`) exist only inside a running
instance; read them live with \`amp_api_spec\` and \`fromManagedInstance: true\`.

Format: \`Module/Method(Param: Type, Optional?: Type) → ReturnType\` [required permission nodes].
Parameter names are exact, including their inconsistent casing. An empty permission list does not
mean anyone may call it: setting reads and writes are still filtered per node.

Grep, don't read top to bottom: \`grep -n "InstanceName" references/api-reference.md\`.
${preLogin ? `
## Callable without a session

\`GetAPISpec\` returns only these before login. If a live spec looks like this list, the session
is not logged in or has expired.

${Object.entries(preLogin).flatMap(([module, methods]) => Object.keys(methods).map((n) => `\`${module}/${n}\``)).join(", ")}
` : ""}
${lines.join("\n")}`;

const out = path.join(root, ".agents", "skills", "amp-mcp", "references", "api-reference.md");
writeFileSync(out, doc);
console.log(`${count(full)} methods (${version}) -> src/amp-api-spec.json, ${path.relative(root, out)}`);
